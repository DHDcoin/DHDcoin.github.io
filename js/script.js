const getInitialLanguage = () => {
    const stored = localStorage.getItem("dhd-lang");
    if (stored && dhdTranslations[stored]) {
        return stored;
    }
    const browserLang = navigator.language ? navigator.language.toLowerCase() : "en";
    return browserLang.startsWith("ru") ? "ru" : "en";
};

let currentLanguage = getInitialLanguage();

const applyLanguage = (lang) => {
    const strings = dhdTranslations[lang];
    if (!strings) {
        return;
    }
    currentLanguage = lang;
    localStorage.setItem("dhd-lang", lang);
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.dataset.i18n;
        const value = strings[key];
        if (value !== undefined) {
            element.textContent = value;
        }
        if (element.dataset.i18nAttr) {
            const attrKey = element.dataset.i18nAttrKey || key;
            const attrValue = strings[attrKey];
            if (attrValue !== undefined) {
                element.setAttribute(element.dataset.i18nAttr, attrValue);
            }
        }
    });

    document.querySelectorAll("[data-i18n-html]").forEach((element) => {
        const value = strings[element.dataset.i18nHtml];
        if (value !== undefined) {
            element.innerHTML = value;
        }
    });

    document.querySelectorAll(".lang-btn").forEach((button) => {
        button.classList.toggle("is-active", button.dataset.lang === lang);
    });

    if (strings.pagepiling_tooltips) {
        document.querySelectorAll("#pp-nav .pp-tooltip").forEach((tooltip, index) => {
            const label = strings.pagepiling_tooltips[index];
            if (label) {
                tooltip.textContent = label;
            }
        });
    }
};

